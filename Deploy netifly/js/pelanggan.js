async function submitPembayaran(e) {
  e.preventDefault();
  const pelangganId = document.getElementById('pay-pelanggan-id').value;
  const tanggal     = document.getElementById('pay-tanggal').value;
  const jumlah      = parseFloat((document.getElementById('pay-jumlah').value||'0').replace(/[^0-9.]/g,''))||0;
  const catatan     = (document.getElementById('pay-catatan').value||'').trim();
  const bukti       = (document.getElementById('pay-bukti').value||'').trim();

  if(!pelangganId || !tanggal) {
    showAlert('Pilih pelanggan dan tanggal bayar.','Validasi');
    return;
  }

  const btn = document.getElementById('btn-submit-pembayaran');
  const orig = btn ? btn.innerHTML : '';
  if(btn) { btn.disabled = true; btn.innerHTML = '<i class="fa-solid fa-spinner animate-spin"></i> Mengirim...'; }

  try {
    const { data: plg } = await supa.from('pelanggan').select('nama, no_layanan').eq('id', pelangganId).single();
    const { error } = await supa.from('pembayaran').insert({
      pelanggan_id:    pelangganId,
      no_layanan:      plg?.no_layanan || '',
      nama_pelanggan:  plg?.nama || '',
      tanggal_bayar:   tanggal,
      jumlah,
      catatan:         catatan || null,
      bukti_url:       bukti   || null,
      status:          'MENUNGGU',
      input_oleh:      currentUser ? currentUser.displayName : 'CS'
    });
    if(error) throw error;
    showAlert(`Pembayaran ${plg?.nama} berhasil dicatat dan menunggu konfirmasi Admin.`,'Terkirim ✅');
    tutupFormPembayaran();
    await loadDataPelanggan();
  } catch(err) {
    showAlert('Gagal simpan pembayaran: '+(err.message||''),'Error');
  }
  if(btn) { btn.disabled = false; btn.innerHTML = orig; }
}

