// ── Helpers ──────────────────────────────────────────────────
function plgText(v) {
  return String(v == null ? '' : v).replace(/[&<>"']/g, c =>
    ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#039;'}[c]));
}
function plgFmt(v) {
  return Number(v||0).toLocaleString('id-ID',{style:'currency',currency:'IDR',maximumFractionDigits:0});
}
function plgDate(s) {
  if(!s) return '-';
  const d = new Date(String(s)+'T00:00:00');
  return d.toLocaleDateString('id-ID',{day:'2-digit',month:'short',year:'numeric'});
}
function plgAddDays(dateStr, days) {
  const d = new Date(String(dateStr)+'T00:00:00');
  d.setDate(d.getDate() + days);
  return d.toISOString().slice(0,10);
}
function plgToday() {
  return new Date().toISOString().slice(0,10);
}
function plgDaysDiff(dateStr) {
  if(!dateStr) return null;
  const diff = new Date(String(dateStr)+'T00:00:00') - new Date(plgToday()+'T00:00:00');
  return Math.ceil(diff / 86400000);
}

function plgStatusBadge(status, tanggalJatuhTempo) {
  const sisa = plgDaysDiff(tanggalJatuhTempo);
  if(status === 'AKTIF') {
    if(sisa !== null && sisa <= 7 && sisa >= 0) {
      return `<span class="px-2.5 py-1 rounded-lg text-[10px] font-extrabold bg-amber-100 text-amber-700 dark:bg-amber-900/40 dark:text-amber-300"><i class="fa-solid fa-triangle-exclamation mr-1"></i>Aktif (Jatuh Tempo ${sisa}h)</span>`;
    }
    return `<span class="px-2.5 py-1 rounded-lg text-[10px] font-extrabold bg-emerald-100 text-emerald-700 dark:bg-emerald-900/40 dark:text-emerald-300"><i class="fa-solid fa-circle-check mr-1"></i>Aktif</span>`;
  }
  if(status === 'SUSPEND') {
    return `<span class="px-2.5 py-1 rounded-lg text-[10px] font-extrabold bg-rose-100 text-rose-700 dark:bg-rose-900/40 dark:text-rose-300 animate-pulse"><i class="fa-solid fa-ban mr-1"></i>Suspend</span>`;
  }
  if(status === 'DISMANTLE') {
    return `<span class="px-2.5 py-1 rounded-lg text-[10px] font-extrabold bg-slate-200 text-slate-600 dark:bg-slate-700 dark:text-slate-400"><i class="fa-solid fa-plug-circle-xmark mr-1"></i>Dismantle</span>`;
  }
  if(status === 'NONAKTIF') {
    return `<span class="px-2.5 py-1 rounded-lg text-[10px] font-extrabold bg-slate-100 text-slate-500"><i class="fa-solid fa-circle-minus mr-1"></i>Nonaktif</span>`;
  }
  return `<span class="px-2.5 py-1 rounded-lg text-[10px] font-extrabold bg-slate-100 text-slate-500">${plgText(status)}</span>`;
}

function plgTipeBadge(tipe) {
  const map = {
    INSTALASI:          'bg-blue-100 text-blue-700',
    INSTALASI_RESELLER: 'bg-cyan-100 text-cyan-700',
    PERLUASAN_RESELLER: 'bg-teal-100 text-teal-700'
  };
  const label = {
    INSTALASI:          'Instalasi Baru',
    INSTALASI_RESELLER: 'Instalasi Reseller',
    PERLUASAN_RESELLER: 'Perluasan'
  };
  return `<span class="px-2 py-0.5 rounded-full text-[9px] font-extrabold ${map[tipe]||'bg-slate-100 text-slate-600'}">${label[tipe]||tipe}</span>`;
}

// ── AUTO BILLING CHECK ────────────────────────────────────────
// Cek semua pelanggan AKTIF/SUSPEND dan update status otomatis
async function runBillingCheck() {
  const today = plgToday();
  try {
    // 1. AKTIF → SUSPEND (jatuh tempo terlewat)
    const { data: toSuspend, error: e1 } = await supa.from('pelanggan')
      .select('id, nama, no_layanan, tanggal_jatuh_tempo')
      .eq('status_billing','AKTIF')
      .lte('tanggal_jatuh_tempo', today);
    if(e1) throw e1;
    for(const p of (toSuspend||[])) {
      await supa.from('pelanggan').update({
        status_billing: 'SUSPEND',
        tanggal_suspend: today,
        updated_at: new Date().toISOString()
      }).eq('id', p.id);
      console.log(`[Billing] ${p.nama} → SUSPEND`);
    }

    // 2. SUSPEND → DISMANTLE (sudah 14 hari sejak suspend)
    const suspendLimit = plgAddDays(today, -14);
    const { data: toDismantle, error: e2 } = await supa.from('pelanggan')
      .select('id, nama, no_layanan, alamat, koordinat, wo_id, teknisi_nama, sumber, mitra_id, mitra_nama')
      .eq('status_billing','SUSPEND')
      .lte('tanggal_suspend', suspendLimit);
    if(e2) throw e2;
    for(const p of (toDismantle||[])) {
      await autoGenerateDismantle(p, today);
    }
  } catch(err) {
    console.warn('[Billing] Auto-check error:', err.message);
  }
}

async function autoGenerateDismantle(pelanggan, today) {
  try {
    // Cek apakah sudah ada dismantle WO untuk pelanggan ini
    const { data: existing } = await supa.from('work_orders')
      .select('wo_id').eq('pelanggan_id', pelanggan.id).eq('is_auto_dismantle', true).maybeSingle();
    if(existing) return; // sudah ada, skip

    // Generate WO dismantle otomatis
    const now = new Date();
    const woId = 'WO-AUTO-' + now.getFullYear().toString().slice(-2)
      + String(now.getMonth()+1).padStart(2,'0')
      + String(now.getDate()).padStart(2,'0')
      + '-' + String(Math.floor(Math.random()*900)+100);

    const { error: woErr } = await supa.from('work_orders').insert({
      wo_id:            woId,
      pelanggan:        pelanggan.nama,
      tipe:             'DISMANTLE',
      cs_name:          'Sistem (Auto Billing)',
      teknisi:          [],
      teknisi_1:        null,
      t1:               now.toTimeString().slice(0,5),
      t2:               now.toTimeString().slice(0,5),
      status:           'RELEASE',
      bulan:            now.getMonth(),
      tahun:            now.getFullYear(),
      tanggal:          today,
      alamat:           pelanggan.alamat || '',
      koordinat:        pelanggan.koordinat || null,
      kendala:          `Auto-dismantle: pelanggan ${pelanggan.nama} (${pelanggan.no_layanan||'-'}) belum bayar 14 hari setelah suspend.`,
      mitra_id:         pelanggan.mitra_id || null,
      is_auto_dismantle: true,
      pelanggan_id:     pelanggan.id,
      released_at:      now.toISOString()
    });
    if(woErr) throw woErr;

    // Update status pelanggan → DISMANTLE
    await supa.from('pelanggan').update({
      status_billing:  'DISMANTLE',
      dismantle_wo_id: woId,
      dismantle_at:    now.toISOString(),
      updated_at:      now.toISOString()
    }).eq('id', pelanggan.id);

    console.log(`[Billing] ${pelanggan.nama} → DISMANTLE, WO: ${woId}`);
  } catch(err) {
    console.warn(`[Billing] Gagal auto-dismantle ${pelanggan.nama}:`, err.message);
  }
}

// ── CREATE PELANGGAN (dipanggil saat WO DONE) ─────────────────
async function createPelangganFromWO(wo) {
  // Cek sudah ada atau belum
  const { data: exists } = await supa.from('pelanggan')
    .select('id').eq('wo_id', wo.wo_id).maybeSingle();
  if(exists) return;

  if(!['INSTALASI','INSTALASI_RESELLER','PERLUASAN_RESELLER'].includes(wo.tipe)) return;

  const today = plgToday();
  const jatuhTempo = plgAddDays(today, 30);

  // Tentukan sumber: cek mitra_id di work_orders
  const sumber = wo.mitra_id ? 'mitra' : 'internal';

  // Ambil nama mitra jika ada
  let mitraNama = null;
  if(wo.mitra_id) {
    const { data: mitra } = await supa.from('mitra').select('nama').eq('id', wo.mitra_id).maybeSingle();
    mitraNama = mitra ? mitra.nama : null;
  }

  await supa.from('pelanggan').insert({
    wo_id:               wo.wo_id,
    no_layanan:          wo.no_layanan || null,
    nama:                wo.pelanggan,
    no_hp:               wo.no_hp || null,
    alamat:              wo.alamat || null,
    koordinat:           wo.koordinat || null,
    paket:               wo.nama_paket || null,
    harga_paket:         wo.paket || 0,
    tipe_instalasi:      wo.tipe,
    tanggal_aktif:       today,
    tanggal_jatuh_tempo: jatuhTempo,
    status_billing:      'AKTIF',
    sumber,
    mitra_id:            wo.mitra_id || null,
    mitra_nama:          mitraNama,
    teknisi_nama:        wo.teknisi_1 || null
  });
}

// ── LOAD DATA PELANGGAN ───────────────────────────────────────
async function loadDataPelanggan() {
  const el = document.getElementById('pelanggan-list');
  if(!el) return;

  // Jalankan billing check dulu
  await runBillingCheck();

  el.innerHTML = '<div class="text-xs text-slate-400 text-center py-6"><i class="fa-solid fa-spinner animate-spin mr-1"></i>Memuat data pelanggan...</div>';

  const statusFilter = (document.getElementById('plg-filter-status')||{value:'SEMUA'}).value || 'SEMUA';
  const tipeFilter   = (document.getElementById('plg-filter-tipe')||{value:'SEMUA'}).value   || 'SEMUA';
  const sumberFilter = (document.getElementById('plg-filter-sumber')||{value:'SEMUA'}).value || 'SEMUA';
  const cariVal      = ((document.getElementById('plg-cari')||{value:''}).value||'').toLowerCase().trim();

  try {
    let query = supa.from('pelanggan')
      .select('*')
      .order('created_at', {ascending: false})
      .limit(500);

    if(statusFilter !== 'SEMUA') query = query.eq('status_billing', statusFilter);
    if(tipeFilter   !== 'SEMUA') query = query.eq('tipe_instalasi', tipeFilter);
    if(sumberFilter !== 'SEMUA') query = query.eq('sumber', sumberFilter);

    const { data, error } = await query;
    if(error) throw error;

    let rows = data || [];
    if(cariVal) {
      rows = rows.filter(p =>
        (p.nama||'').toLowerCase().includes(cariVal) ||
        (p.no_layanan||'').toLowerCase().includes(cariVal) ||
        (p.no_hp||'').toLowerCase().includes(cariVal) ||
        (p.alamat||'').toLowerCase().includes(cariVal)
      );
    }
    _pelangganData = rows;

    if(!rows.length) {
      el.innerHTML = '<div class="text-xs text-slate-400 text-center py-8"><i class="fa-solid fa-inbox text-2xl block mb-2"></i>Tidak ada data pelanggan.</div>';
      updatePelangganSummary([]);
      return;
    }

    updatePelangganSummary(rows);
    renderPelangganTable(rows);
  } catch(err) {
    el.innerHTML = `<div class="text-xs text-rose-500 text-center py-4">Gagal memuat: ${plgText(err.message)}</div>`;
  }
}

function updatePelangganSummary(rows) {
  const aktif    = rows.filter(p => p.status_billing === 'AKTIF').length;
  const suspend  = rows.filter(p => p.status_billing === 'SUSPEND').length;
  const dismantle= rows.filter(p => p.status_billing === 'DISMANTLE').length;
  const total    = rows.length;

  const set = (id, val) => { const el = document.getElementById(id); if(el) el.textContent = val; };
  set('plg-summary-total',    total);
  set('plg-summary-aktif',    aktif);
  set('plg-summary-suspend',  suspend);
  set('plg-summary-dismantle',dismantle);
}

