async function konfirmasiPembayaran(payId, pelangganId, tanggalBayar, approve) {
  const btn = event.target.closest('button');
  const origHtml = btn ? btn.innerHTML : '';
  if(btn) { btn.disabled = true; btn.innerHTML = '<i class="fa-solid fa-spinner animate-spin"></i>'; }
  try {
    const status = approve ? 'DIKONFIRMASI' : 'DITOLAK';
    const { error: payErr } = await supa.from('pembayaran').update({
      status,
      konfirmasi_oleh: currentUser ? currentUser.displayName : 'Admin',
      konfirmasi_at:   new Date().toISOString()
    }).eq('id', payId);
    if(payErr) throw payErr;

    if(approve) {
      // Update status pelanggan → AKTIF, hitung jatuh tempo baru
      const jatuhTempo = plgAddDays(tanggalBayar, 30);
      const { error: plgErr } = await supa.from('pelanggan').update({
        status_billing:          'AKTIF',
        tanggal_bayar_terakhir:  tanggalBayar,
        tanggal_jatuh_tempo:     jatuhTempo,
        tanggal_suspend:         null,
        updated_at:              new Date().toISOString()
      }).eq('id', pelangganId);
      if(plgErr) throw plgErr;
      showAlert(`Pembayaran dikonfirmasi. Pelanggan aktif kembali.\nJatuh tempo berikutnya: ${plgDate(jatuhTempo)}`,'Berhasil ✅');
    } else {
      showAlert('Pembayaran ditolak.','Ditolak');
    }
    await loadKonfirmasiPembayaran();
  } catch(err) {
    showAlert('Gagal konfirmasi: '+(err.message||''),'Error');
  }
  if(btn) { btn.disabled = false; btn.innerHTML = origHtml; }
}

